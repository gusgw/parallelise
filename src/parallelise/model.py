"""The client for an OpenAI-compatible chat endpoint, and the meter that every call goes through.

One ``Meter`` serves a whole run. Every HTTP client that reaches the model, the plain agent's
and the frameworks' alike, sends its requests through a transport that the meter makes, so
each answer is timed and its tokens counted once, in the same way, whichever agent design
asked. The same transport waits out HTTP 429 (too many requests): a shared model service often
refuses requests for a while when it is busy, and giving up at the first refusal would end a run
that only needed to wait. The wait is the number of seconds in the ``Retry-After`` header when
there is one, and otherwise doubles from two seconds up to thirty; the waits for one request are
limited, in total, by ``Settings.throttle_wait_s``.
"""

from __future__ import annotations

import asyncio
import logging
import math
import time
from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from functools import cache
from typing import Any

import httpx

from .config import Settings
from .errors import ModelError, ParalleliseError

log = logging.getLogger("parallelise.model")

MAX_ATTEMPTS = 3
FIRST_WAIT_S, LONGEST_WAIT_S, SHORTEST_WAIT_S = 2.0, 30.0, 1.0


class Throttle:
    """Decides how long to wait after each HTTP 429 answer to one request, or to give up."""

    def __init__(self, allowance_s: float) -> None:
        self.allowance_s, self.waited_s, self.answers = allowance_s, 0.0, 0

    def next_wait(self, retry_after: str | None) -> float | None:
        """Return the seconds to wait before asking again, or None to give up.

        A ``Retry-After`` of a number of seconds is obeyed, but never less than one second, and
        if it is more than what is left of the allowance there is no point in waiting at all.
        """
        self.answers += 1
        left = self.allowance_s - self.waited_s
        try:
            told = float(retry_after) if retry_after is not None else math.nan
        except ValueError:
            told = math.nan
        if math.isfinite(told) and told >= 0:
            wait = max(told, SHORTEST_WAIT_S)
            if wait > left:
                return None
        else:
            wait = min(FIRST_WAIT_S * 2 ** min(self.answers - 1, 20), LONGEST_WAIT_S, left)
        if wait <= 0:
            return None
        self.waited_s += wait
        log.warning("the endpoint answered HTTP 429 (too many requests); waiting %g seconds "
                    "(%g of %g seconds of waiting used)", wait, self.waited_s, self.allowance_s)
        return wait


@dataclass
class Call:
    """One accepted answer of the model: how long it took and the tokens it used."""

    latency_s: float
    prompt_tokens: int
    completion_tokens: int


class Meter:
    """Times and counts the model's answers, and waits out its refusals, for one run.

    ``sleep`` and ``async_sleep`` replace the waits, for tests.
    """

    def __init__(self, throttle_wait_s: float, sleep: Callable[[float], None] = time.sleep,
                 async_sleep: Callable[[float], Awaitable[None]] = asyncio.sleep) -> None:
        self.throttle_wait_s, self.sleep, self.async_sleep = throttle_wait_s, sleep, async_sleep
        self.calls: list[Call] = []

    def record(self, request: Any, response: Any, elapsed: float) -> None:
        """Count an accepted answer to a chat request."""
        if response.status_code >= 400 or not request.url.path.endswith("chat/completions"):
            return
        try:
            usage = response.json().get("usage") or {}
        except (ValueError, AttributeError):
            usage = {}
        self.calls.append(Call(elapsed, int(usage.get("prompt_tokens") or 0),
                               int(usage.get("completion_tokens") or 0)))  # fmt: skip

    def transport(self) -> httpx.BaseTransport:
        """A transport for an ``httpx.Client`` that reaches the model."""
        return _MeteredTransport(self, httpx.HTTPTransport())

    def async_transport(self, library: Any = httpx) -> Any:
        """A transport for an asynchronous client of ``library``: httpx, or httpx2, which
        Pydantic AI uses."""
        return _async_transport_class(library)(self, library.AsyncHTTPTransport())

    def summary(self) -> dict[str, Any]:
        """The requests, tokens, mean latency and completion tokens per second so far.

        The rate divides the tokens generated by the time spent waiting for answers, so it
        measures the endpoint and not the agent's own work between calls.
        """
        waiting = sum(c.latency_s for c in self.calls)
        completion = sum(c.completion_tokens for c in self.calls)
        return {
            "requests": len(self.calls),
            "prompt_tokens": sum(c.prompt_tokens for c in self.calls),
            "completion_tokens": completion,
            "latency_mean_s": waiting / len(self.calls) if self.calls else 0.0,
            "tokens_per_second": completion / waiting if waiting > 0 else 0.0,
        }


class _MeteredTransport(httpx.BaseTransport):
    def __init__(self, meter: Meter, inner: httpx.BaseTransport) -> None:
        self.meter, self.inner = meter, inner

    def handle_request(self, request: httpx.Request) -> httpx.Response:
        throttle = Throttle(self.meter.throttle_wait_s)
        while True:
            started = time.perf_counter()
            response = self.inner.handle_request(request)
            if response.status_code == 429:
                wait = throttle.next_wait(response.headers.get("retry-after"))
                if wait is not None:
                    response.close()
                    self.meter.sleep(wait)
                    continue
                # The OpenAI library obeys this, and so does not wait all over again.
                response.headers["x-should-retry"] = "false"
            response.read()
            self.meter.record(request, response, time.perf_counter() - started)
            return response

    def close(self) -> None:
        self.inner.close()


@cache
def _async_transport_class(library: Any) -> Any:
    """The asynchronous form of ``_MeteredTransport``, for httpx or for httpx2."""

    class _MeteredAsyncTransport(library.AsyncBaseTransport):  # type: ignore[misc, name-defined]
        def __init__(self, meter: Meter, inner: Any) -> None:
            self.meter, self.inner = meter, inner

        async def handle_async_request(self, request: Any) -> Any:
            throttle = Throttle(self.meter.throttle_wait_s)
            while True:
                started = time.perf_counter()
                response = await self.inner.handle_async_request(request)
                if response.status_code == 429:
                    wait = throttle.next_wait(response.headers.get("retry-after"))
                    if wait is not None:
                        await response.aclose()
                        await self.meter.async_sleep(wait)
                        continue
                    response.headers["x-should-retry"] = "false"
                await response.aread()
                self.meter.record(request, response, time.perf_counter() - started)
                return response

        async def aclose(self) -> None:
            await self.inner.aclose()

    return _MeteredAsyncTransport


class ModelClient:
    """Calls a chat-completions endpoint, through a meter that counts every answer.

    ``retry_delay_s`` is the wait before the second attempt after a connection error or a
    server error, doubled for the third; ``sleep`` replaces the waits, for tests.
    """

    def __init__(self, settings: Settings, retry_delay_s: float = 2.0,
                 sleep: Callable[[float], None] = time.sleep) -> None:
        self.settings, self.retry_delay_s, self.sleep = settings, retry_delay_s, sleep
        self.meter = Meter(settings.throttle_wait_s, sleep)
        headers = {"Authorization": f"Bearer {settings.api_key}"} if settings.api_key else {}
        try:
            self._http = httpx.Client(base_url=settings.gateway_url.rstrip("/") + "/",
                                      headers=headers, timeout=settings.request_timeout_s,
                                      transport=self.meter.transport())  # fmt: skip
        except httpx.InvalidURL as exc:
            raise ParalleliseError(
                f"The gateway URL {settings.gateway_url!r} is not a usable web address ({exc}). "
                "Set PARALLELISE_GATEWAY_URL, for example to http://localhost:4000/v1."
            ) from exc

    def close(self) -> None:
        self._http.close()

    def __enter__(self) -> ModelClient:
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def chat(self, messages: list[dict[str, Any]],
             tools: list[dict[str, Any]] | None = None) -> dict[str, Any]:  # fmt: skip
        """Send one chat request and return the assistant's message.

        Connection errors and server errors (HTTP 5xx) are tried again, up to three attempts
        in all. HTTP 429 is waited out by the meter's transport. Other client errors (HTTP 4xx)
        are not tried again, because repeating a bad request cannot help.
        """
        payload: dict[str, Any] = {"model": self.settings.model, "messages": messages,
                                   "temperature": self.settings.temperature}  # fmt: skip
        if tools:
            payload["tools"] = tools
        problem = ""
        for attempt in range(1, MAX_ATTEMPTS + 1):
            try:
                response = self._http.post("chat/completions", json=payload)
            except httpx.TransportError as exc:
                problem = f"could not reach {self.settings.gateway_url} ({exc})"
            else:
                status = response.status_code
                if status == 429:
                    raise ModelError(
                        "The endpoint kept answering HTTP 429 (too many requests) for the "
                        f"{self.settings.throttle_wait_s:g} seconds of waiting allowed. Try "
                        "again later, lower the load on the gateway, or raise "
                        "PARALLELISE_THROTTLE_WAIT."
                    )
                if status < 400:
                    return _message(response)
                if status < 500:
                    raise ModelError(
                        f"The endpoint rejected the request with HTTP {status}: "
                        f"{response.text[:300]!r}. Check the model name "
                        f"({self.settings.model!r}) and the API key."
                    )
                problem = f"the endpoint returned HTTP {status}"
            log.warning("attempt %d of %d: %s", attempt, MAX_ATTEMPTS, problem)
            if attempt < MAX_ATTEMPTS:
                self.sleep(self.retry_delay_s * attempt)
        raise ModelError(
            f"The model call failed after {MAX_ATTEMPTS} attempts: {problem}. "
            "Check that the gateway is running (parallelise health)."
        )

    def models(self) -> list[str]:
        """Return the models that the endpoint offers; raise ModelError if it cannot say."""
        try:
            response = self._http.get("models", timeout=min(30.0, self.settings.request_timeout_s))
            response.raise_for_status()
            return [str(m["id"]) for m in response.json()["data"]]
        except httpx.TransportError as exc:
            raise ModelError(f"Could not reach {self.settings.gateway_url} ({exc}). Start the "
                             "gateway or set PARALLELISE_GATEWAY_URL.") from exc
        except (httpx.HTTPStatusError, ValueError, KeyError, TypeError) as exc:
            raise ModelError(f"The endpoint gave no list of models ({exc}). Check the API key "
                             "and that the URL ends in /v1.") from exc


def _message(response: httpx.Response) -> dict[str, Any]:
    """The assistant's message in a chat completion, with empty content rather than none."""
    try:
        message = dict(response.json()["choices"][0]["message"])
    except (ValueError, KeyError, IndexError, TypeError) as exc:
        raise ModelError(
            "The endpoint answered, but the reply is not a chat completion "
            f"({type(exc).__name__}). Check that the URL ends in /v1 and names an "
            "OpenAI-compatible server."
        ) from exc
    if message.get("content") is None:
        message["content"] = ""
    return message
